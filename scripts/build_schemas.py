#!/usr/bin/env python3
"""Bake swagger request shapes into a checked-in lookup for ``--help`` output.

Generic commands (``src/sylve_cli/commands/extras.py``) accept arbitrary
``--set KEY=VALUE`` fields, so users need a per-command field list. The
installed package does not ship ``docs/swagger.json``, so this script reads
the spec at build time and writes ``src/sylve_cli/body_schemas.py``. Run
``make schemas`` after changing ``docs/swagger.json`` or the spec lists;
CI enforces freshness with ``--check``.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "docs" / "swagger.json"
EXTRAS = ROOT / "src" / "sylve_cli" / "commands" / "extras.py"
OUTPUT = ROOT / "src" / "sylve_cli" / "body_schemas.py"

SPEC_RE = re.compile(r'\(\s*\w+_app,\s*"([^"]+)",\s*"(GET|POST|PUT|PATCH|DELETE)",\s*"([^"]+)"')


def short_type(schema: dict, defs: dict, depth: int = 0) -> str:
    """Render a swagger property schema as a short type name.

    Object references expand two levels (``object {a, b: object {x}}``) so
    ``--set`` dotted keys stay discoverable; deeper nesting is a bare name.
    """
    if "$ref" in schema:
        name = schema["$ref"].split("/")[-1]
        if depth > 1:
            return name.split(".")[-1]
        props = defs.get(name, {}).get("properties", {})
        if not props:
            return "object"
        inner = ", ".join(
            f"{k}: {short_type(v, defs, depth + 1)}" for k, v in sorted(props.items())
        )
        return "object {" + inner + "}"
    kind = str(schema.get("type", ""))
    if kind == "array":
        items = schema.get("items", {})
        return f"array of {short_type(items, defs, depth + 1)}" if items else "array"
    return kind or "value"


def build() -> dict:
    """Map (METHOD, path) to required/optional body and query fields."""
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    defs = spec.get("definitions", {})
    paths = spec.get("paths", {})
    seen: set[tuple[str, str]] = set()
    for match in SPEC_RE.finditer(EXTRAS.read_text(encoding="utf-8")):
        _, method, path = match.groups()
        seen.add((method, path))

    result: dict[tuple[str, str], dict] = {}
    for method, path in sorted(seen):
        op = paths.get(path, {}).get(method.lower(), {})
        entry: dict[str, object] = {"body": {}, "body_required": [], "query": {}}
        for param in op.get("parameters", []):
            if param.get("in") == "body":
                ref = (param.get("schema", {}) or {}).get("$ref", "")
                definition = defs.get(ref.split("/")[-1], {})
                props = definition.get("properties", {})
                entry["body"] = {k: short_type(v, defs) for k, v in props.items()}
                entry["body_required"] = list(definition.get("required", []))
            elif param.get("in") == "query":
                query = entry["query"]
                assert isinstance(query, dict)
                query[param["name"]] = short_type(param, defs)
                if param.get("required"):
                    required = entry.setdefault("query_required", [])
                    assert isinstance(required, list)
                    required.append(param["name"])
        result[(method, path)] = entry
    return result


def render(mapping: dict) -> str:
    """Render the mapping as an importable Python module."""
    lines = [
        '"""Request shapes for generic commands, per ``--help`` field lists.',
        "",
        "Code generated by ``scripts/build_schemas.py`` from ``docs/swagger.json``.",
        "Do not edit; run ``make schemas`` instead.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "BODY_SCHEMAS: dict[tuple[str, str], dict] = {",
    ]
    for (method, path), entry in mapping.items():
        body = entry["body"]
        assert isinstance(body, dict)
        query = entry["query"]
        assert isinstance(query, dict)
        body_req = entry["body_required"]
        assert isinstance(body_req, list)
        query_req = entry.get("query_required", [])
        assert isinstance(query_req, list)
        lines.append(f"    ({method!r}, {path!r}): {{")
        lines.append(f'        "body_required": {body_req!r},')
        lines.append('        "body": {')
        for name in sorted(body):
            lines.append(f"            {name!r}: {body[name]!r},")
        lines.append("        },")
        lines.append('        "query": {')
        for name in sorted(query):
            lines.append(f"            {name!r}: {query[name]!r},")
        lines.append("        },")
        lines.append(f'        "query_required": {query_req!r},')
        lines.append("    },")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    """Write the module, or verify it is current with ``--check``."""
    check = "--check" in sys.argv[1:]
    rendered = render(build())
    if check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered:
            print(f"out of date: {OUTPUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"rendered {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
